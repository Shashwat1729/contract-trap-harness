#!/usr/bin/env python3
"""
Evaluation harness — baseline vs advanced.
- Hit both services (or run in mock mode without network)
- Compute metrics: success_rate, latency_p95, edge_pass, cost
- Write evidence/benchmarks/results.json + results.md + comparison.md

Usage:
  python scripts/eval.py --baseline http://localhost:8000 --advanced http://localhost:8001
  EVAL_MOCK=1 python scripts/eval.py   # no network, deterministic fake data

At kickoff: replace QUERIES + metrics with real acceptance tests from PDF.
"""
import argparse, json, os, time, statistics, urllib.request, urllib.error
from pathlib import Path

ROOT = Path(__file__).parents[1]
OUT_JSON = ROOT / "evidence/benchmarks/results.json"
OUT_MD = ROOT / "evidence/benchmarks/results.md"
OUT_CMP = ROOT / "evidence/benchmarks/comparison.md"

# Template queries — replace with acceptance test fixtures at kickoff
QUERIES = ["hello", "edge case: empty", "normal task", "another query", "stress test 5"]

def fetch(base_url: str, q: str):
    url = f"{base_url}/api/example?q={urllib.parse.quote(q)}"
    t0 = time.perf_counter()
    try:
        with urllib.request.urlopen(url, timeout=5) as r:
            body = json.loads(r.read().decode())
            ok = r.status == 200 and "result" in body
            return ok, time.perf_counter() - t0, body
    except Exception as e:
        return False, time.perf_counter() - t0, {"error": str(e)}

def eval_variant(name: str, base_url: str, mock: bool):
    results = []
    latencies = []
    ok_count = 0
    for q in QUERIES:
        if mock:
            # Deterministic mock: advanced slightly better
            lat = 0.12 if name == "advanced" else 0.25
            ok = True if name == "advanced" else (q != "edge case: empty")
            body = {"result": f"{name} mock for {q}"}
        else:
            ok, lat, body = fetch(base_url, q)
        latencies.append(lat)
        ok_count += int(ok)
        results.append({"query": q, "ok": ok, "latency": round(lat, 4), "body": body})
    p95 = sorted(latencies)[int(0.95 * len(latencies))] if latencies else 0
    mean = statistics.mean(latencies) if latencies else 0
    return {
        "variant": name,
        "base_url": base_url,
        "success_rate": round(ok_count / len(QUERIES), 3) if QUERIES else 0,
        "mean_latency": round(mean, 4),
        "p95_latency": round(p95, 4),
        "edge_pass": ok_count,  # template — replace with real edge count
        "per_query": results,
    }

def write_outputs(baseline, advanced):
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "queries": QUERIES,
        "baseline": baseline,
        "advanced": advanced,
        "deltas": {
            "success_rate": round(advanced["success_rate"] - baseline["success_rate"], 3),
            "p95_latency": round(advanced["p95_latency"] - baseline["p95_latency"], 4),
            "note": "positive success delta = win; negative latency delta = win",
        }
    }
    OUT_JSON.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(f"[eval] wrote {OUT_JSON}")

    # results.md
    md = f"""# Benchmark Results — {payload['timestamp']}

| Variant | Success | Mean Lat | p95 Lat | Edge Pass |
|---------|---------|----------|---------|-----------|
| baseline | {baseline['success_rate']*100:.1f}% | {baseline['mean_latency']}s | {baseline['p95_latency']}s | {baseline['edge_pass']}/{len(QUERIES)} |
| advanced | {advanced['success_rate']*100:.1f}% | {advanced['mean_latency']}s | {advanced['p95_latency']}s | {advanced['edge_pass']}/{len(QUERIES)} |

Delta: success {payload['deltas']['success_rate']:+.1%}, p95 {payload['deltas']['p95_latency']:+.4f}s
"""
    OUT_MD.write_text(md, encoding="utf-8")
    print(f"[eval] wrote {OUT_MD}")

    # comparison.md — the money slide (use ASCII-safe markers for Windows cp1252 compatibility, but keep emoji)
    success_icon = "[PASS]" if payload['deltas']['success_rate'] >= 0 else "[FAIL]"
    latency_icon = "[PASS]" if payload['deltas']['p95_latency'] <= 0 else "[FAIL]"
    cmp = f"""# Baseline vs Advanced — Comparison

> Auto-generated by `make eval`. This is the slide judges see first after the video.

| Metric | Baseline | Advanced | Delta | Verdict |
|--------|----------|----------|-------|---------|
| Success rate | {baseline['success_rate']:.1%} | {advanced['success_rate']:.1%} | {payload['deltas']['success_rate']:+.1%} | {success_icon} |
| p95 latency | {baseline['p95_latency']:.3f}s | {advanced['p95_latency']:.3f}s | {payload['deltas']['p95_latency']:+.3f}s | {latency_icon} |
| Edge cases passed | {baseline['edge_pass']}/{len(QUERIES)} | {advanced['edge_pass']}/{len(QUERIES)} | {advanced['edge_pass']-baseline['edge_pass']:+d} | — |

**Datasets:** `{QUERIES}` (template — replace at kickoff)  
**Reproduce:** `EVAL_MOCK=1 make eval` or `make eval` with live services  
**Evidence:** `evidence/benchmarks/results.json`
"""
    OUT_CMP.write_text(cmp, encoding="utf-8")
    print(f"[eval] wrote {OUT_CMP}")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--baseline", default="http://localhost:8000")
    ap.add_argument("--advanced", default="http://localhost:8001")
    args = ap.parse_args()
    mock = os.getenv("EVAL_MOCK", "0") == "1"
    if mock:
        print("[eval] EVAL_MOCK=1 — using deterministic mock (no network)")
    import urllib.parse  # ensure available
    baseline = eval_variant("baseline", args.baseline, mock)
    advanced = eval_variant("advanced", args.advanced, mock)
    write_outputs(baseline, advanced)
    print(f"[eval] baseline {baseline['success_rate']:.0%} p95={baseline['p95_latency']:.3f}s | advanced {advanced['success_rate']:.0%} p95={advanced['p95_latency']:.3f}s")

if __name__ == "__main__":
    main()
